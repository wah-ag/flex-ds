// A token's value in a mode: the last layer that defines it wins, and each
// var() is followed until it reaches a literal.
function resolve(name, layers, stack = []) {
  if (stack.includes(name)) fail(`circular token: ${[...stack, name].join(' -> ')}`);
  let value = null;
  for (const l of layers) if (l.has(name)) value = l.get(name);
  if (value === null) return null;
  return value.replace(/var\(--([\w-]+)\)/g, (whole, n) => resolve(n, layers, [...stack, name]) ?? whole);
}
const light = (n) => resolve(n, [LIGHT]);
const dark = (n) => resolve(n, [LIGHT, DARK]);
const backOffice = (n) => resolve(n, [LIGHT, BACK]);

// Semantic tokens: the leaves of the semantic collections in tokens/
// (read-only), named as the build names them.
function leaves(file) {
  const out = [];
  (function walk(o, p) {
    for (const [k, v] of Object.entries(o)) {
      if (k.startsWith('$')) continue;
      if (v && typeof v === 'object' && '$value' in v) out.push([...p, k].join('-').toLowerCase().replace(/[^a-z0-9-]+/g, '-'));
      else if (v && typeof v === 'object') walk(v, [...p, k]);
    }
  })(JSON.parse(read(file)), []);
  return out;
}
