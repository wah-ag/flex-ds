// A source reference ("src/x.jsx:12" or "Figma 17:826 (...)") as a link.
function sourceLink(src, figmaBase) {
  const file = src.match(/^((?:src|docs|stories)\/[^\s:]+)(?::(\d+))?/);
  if (file) return `<a href="${attr(blob(file[1], file[2]))}">${esc(src)}</a>`;
  const fig = src.match(/^Figma (\d+:\d+)/);
  if (fig && figmaBase) return `<a href="${attr(nodeUrl(figmaBase, fig[1]))}">${esc(src)}</a>`;
  return esc(src);
}

