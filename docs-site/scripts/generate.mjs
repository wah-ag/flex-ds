// The component's signature, defaults and the comment block above it.
function signature(folder) {
  const file = `src/components/${folder}/${folder}.jsx`;
  const src = read(file);
  const lines = src.split('\n');
  const start = lines.findIndex((l) => l.startsWith(`export function ${folder}(`));
  if (start < 0) fail(`${file}: no "export function ${folder}("`);
  let body = '';
  let end = start;
  for (; end < lines.length; end++) {
    body += lines[end] + '\n';
    if (/\}\)\s*\{\s*$/.test(lines[end])) break;
  }
  const inner = body.slice(body.indexOf('({') + 2, body.lastIndexOf('})'));
  const props = [];
  let depth = 0;
  let cur = '';
  let quote = null;
  for (const ch of inner) {
    if (quote) { if (ch === quote) quote = null; cur += ch; continue; }
    if (`'"\``.includes(ch)) quote = ch;
    if ('([{'.includes(ch)) depth++;
    if (')]}'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) { props.push(cur); cur = ''; } else cur += ch;
  }
  props.push(cur);
  const parsed = props.map((p) => p.trim()).filter(Boolean).map((p) => {
    if (p.startsWith('...')) return { rest: p.slice(3) };
    const m = p.match(/^(\w+)(?:\s*:\s*\w+)?(?:\s*=\s*([\s\S]+))?$/);
    if (!m) fail(`${file}: cannot read prop "${p}"`);
    return { name: m[1], def: m[2]?.trim() ?? null };
  });
  for (const p of parsed) if (p.name) p.line = start + 1 + lines.slice(start, end + 1).findIndex((l) => new RegExp(`\\b${p.name}\\b`).test(l));
  const comment = [];
  for (let i = start - 1; i >= 0 && lines[i].startsWith('//'); i--) comment.unshift(lines[i].replace(/^\/\/ ?/, ''));
  const commentStart = start - comment.length + 1;
  return { file, line: start + 1, props: parsed, comment, commentStart };
}

// The published declaration for a component, member by member.
function declaration(folder) {
  const m = dts.match(new RegExp(`declare function ${folder}\\([^)]*\\}: \\{([\\s\\S]*?)\\n\\}\\): any;`));
  if (!m) return null;
  const types = new Map();
  for (const line of m[1].split('\n')) {
    const t = line.trim().match(/^(\w+)(\??): (.+);$/);
    if (t) types.set(t[1], { optional: t[2] === '?', type: t[3] });
  }
  return types;
}

// Stories: the variant-matrix rule. A story is a variant-matrix row when
// its stories file exports it from the file's cell() factory, one Figma
// variant per story. Every other story is an example. Applied the same way
// on Examples and Design, so a story is never on both.
function stories(folder) {
  const file = `src/components/${folder}/${folder}.stories.jsx`;
  const src = read(file);
  const title = (src.match(/title:\s*'([^']+)'/) ?? fail(`${file}: no title`))[1];
  const params = (src.match(/const cell = \(([^)]*)\)/)?.[1] ?? '').split(',').map((s) => s.trim()).filter(Boolean);
  const cells = new Map();
  for (const m of src.matchAll(/^export const (\w+) = cell\(([^)]*)\);/gm)) {
    const args = [...m[2].matchAll(/'([^']*)'/g)].map((a) => a[1]);
    cells.set(m[1], Object.fromEntries(params.map((p, i) => [p, args[i]])));
  }
  const options = new Map();
  src.split('\n').forEach((l, i) => {
    const o = l.match(/^\s*(\w+): \{ control: '[^']+', options: \[([^\]]*)\]/);
    if (o && /^\s*'/.test(o[2])) options.set(o[1], { values: [...o[2].matchAll(/'([^']*)'/g)].map((a) => a[1]), line: i + 1 });
  });
  const entries = sbEntries.filter((e) => e.title === title && e.type === 'story');
  const docs = sbEntries.filter((e) => e.title === title && e.type === 'docs');
  for (const e of entries) e.cell = cells.get(e.exportName) ?? null;
  return { file, title, entries, docs, options, cellParams: params };
}
