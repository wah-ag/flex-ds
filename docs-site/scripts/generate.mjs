function tokenTable(names) {
  const rows = names.map((n) => {
    const bare = n.replace(/^--/, '');
    if (!LIGHT.has(bare)) return `| ${code(n)} | **missing from the build** | |`;
    return `| ${code(n)} | ${code(light(bare))} | ${code(dark(bare))} |`;
  });
  return ['| Token | on-light | on-dark |', '| --- | --- | --- |', ...rows].join('\n');
}

